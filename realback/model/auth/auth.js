const mongoose = require("mongoose");

const authSchema = mongoose.Schema({
  name: {
    type: String,
    require: true,
  },
  email: {
    type: String,
    require: true,
    unique: true,
  },
  password: {
    type: String,
    require: true,
  },
});

const auth = mongoose.model("auth", authSchema);

module.exports = auth;